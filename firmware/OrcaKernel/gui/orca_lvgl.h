#ifndef ORCA_LVGL_H
#define ORCA_LVGL_H

#include <stdint.h>
#include <stdbool.h>

/*
 * GUI на LVGL: реальный интерфейс устройства, а не тестовая картинка.
 *
 * Тракт кадра сейчас такой:
 *
 *   LVGL рисует в ORCA_FB_SLOT_GUI (SDRAM, RGB565, режим DIRECT)
 *     -> flush_cb на последней области копирует кадр в ORCA_FB_SLOT_GUI_TX
 *     -> задача gui_tx отдаёт снимок в orca_fbstream -> Orca Link -> ПК
 *
 * Копия нужна из-за того, что отправка кадра синхронная и очень медленная:
 * 240x160 RGB565 на UART 921600 уходит ~0.8 с (HAL_UART_Transmit блокирующий).
 * Если пушить прямо из flush_cb, задача LVGL встаёт на всё это время — анимации
 * дёргаются, а тач обрабатывается раз в секунду. Поэтому отрисовка и передача
 * разведены по задачам, а снимок гарантирует, что клиент получит целый кадр,
 * а не половину старого и половину нового.
 *
 * Когда появится LTDC, слот GUI станет фреймбуфером панели и здесь поменяется
 * только flush_cb: контракт с orca_fbstream останется тем же.
 */

/*
 * Размер экрана. Должен совпадать с окном клиента (SCREEN_W/SCREEN_H в
 * tools/fbstream/orca_view.py) и с ORCA_FBTEST_WIDTH/HEIGHT: клиент считает
 * координаты тача в этой системе и растягивает пришедший кадр под неё.
 */
#define ORCA_GUI_WIDTH   480u
#define ORCA_GUI_HEIGHT  320u

/*
 * Поднимает LVGL, дисплей, ввод и строит интерфейс. Требует поднятой SDRAM:
 * там лежат и куча LVGL (LV_MEM_ADR), и оба кадровых буфера. false — GUI не
 * запустился, вызывающий должен переключить трансляцию на fbtest.
 */
bool orca_lvgl_init(void);

/* Цикл lv_timer_handler: отрисовка, анимации, таймеры, опрос ввода. */
void orca_lvgl_task(void* arg);

/* Отправка готовых кадров в orca_fbstream. Отдельная задача — см. выше. */
void orca_lvgl_stream_task(void* arg);

/* Сколько кадров отрисовал LVGL — для shell `fb status`. */
uint32_t orca_lvgl_frame_count(void);

/*
 * Сколько раз задача GUI прокрутила lv_timer_handler. Вместе с
 * frame_count различает три разных отказа, которые снаружи выглядят
 * одинаково («экран не обновляется»): счётчик стоит на нуле — задача не
 * работает вообще; растёт, а кадры нет — LVGL нечего перерисовывать (или
 * встали его таймеры); растут оба, а на ПК пусто — потерялась передача.
 */
uint32_t orca_lvgl_loop_count(void);

/* Занято в куче LVGL, байт (LV_MEM_SIZE минус свободное). */
uint32_t orca_lvgl_heap_used(void);

#endif /* ORCA_LVGL_H */
