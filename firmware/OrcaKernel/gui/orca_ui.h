#ifndef ORCA_UI_H
#define ORCA_UI_H

#include <stdint.h>
#include <stdbool.h>

/*
 * Интерфейс устройства описан не кодом, а страницами на SD-карте:
 * 0:/gui/main.ui — главный экран, 0:/gui/apps.ui — список приложений,
 * дальше сколько угодно своих файлов (переход по кнопке goto=<имя>).
 *
 * Зачем так, а не lv_obj_create в прошивке: экран меняется на порядок чаще
 * ядра, а перепрошивка ради переставленной карточки — это DFU, BOOT0 и
 * потерянные настройки. Файл на карте правится текстовым редактором и
 * применяется командой `gui reload`, без сборки и без перезагрузки.
 *
 * Формат разобран в orca_ui.c (там же список виджетов, атрибутов и bind'ов).
 *
 * Встроенная копия main/apps остаётся в прошивке: без карты (или с пустым
 * 0:/gui) устройство обязано показать рабочий экран, а не чёрный кадр.
 */

#define ORCA_UI_DIR      "0:/gui"
#define ORCA_UI_EXT      ".ui"
#define ORCA_UI_HOME     "main"

/* Имя страницы — это имя файла, поэтому ограничение то же, что у cmdfs. */
#define ORCA_UI_NAME_MAX 24u

/* Больше страница быть не может: буфер разбора статический (см. orca_ui.c). */
#define ORCA_UI_FILE_MAX 4096u

/*
 * Строит домашнюю страницу (ORCA_UI_HOME). Вызывается из orca_lvgl_init
 * после создания дисплея: без активного экрана LVGL рисовать нечего.
 */
bool orca_ui_init(void);

/*
 * Переход на страницу по имени файла без каталога и расширения.
 * Возвращает false, если такой страницы нет ни на карте, ни внутри прошивки.
 *
 * Сам экран пересобирается не здесь, а на следующем витке задачи GUI (~50 мс):
 * вызов приходит либо из колбэка кнопки — а удалять экран, которому эта кнопка
 * принадлежит, посреди обработки её события нельзя, — либо вообще из чужой
 * задачи (shell), которой в дерево виджетов LVGL лезть нечем.
 */
bool orca_ui_open(const char* name);

/* Перечитать текущую страницу с карты — shell `gui reload`. */
bool orca_ui_reload(void);

/* Имя текущей страницы. */
const char* orca_ui_current(void);

/* true — страница прочитана с карты, false — взята встроенная копия. */
bool orca_ui_from_card(void);

/*
 * Сбросить кэш списка приложений: каталог 0:/apps мог измениться, пока
 * карта была отдана хосту по USB (см. orca_usb_msc.c).
 */
void orca_ui_apps_changed(void);

#endif /* ORCA_UI_H */
