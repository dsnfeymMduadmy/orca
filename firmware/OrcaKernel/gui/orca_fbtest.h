#ifndef ORCA_FBTEST_H
#define ORCA_FBTEST_H

#include <stdint.h>
#include <stdbool.h>

/*
 * Синтетический источник кадров: рисует анимированную картинку в SDRAM и
 * отдаёт её в orca_fbstream. Нужен, пока физического дисплея нет —
 * позволяет проверить весь путь "SDRAM -> Orca Link -> UART -> ПК" на
 * одной плате, без LCD и без ESP32.
 *
 * Когда появится LTDC, эта задача заменяется реальным GUI-движком:
 * контракт с fbstream (orca_fbstream_push_frame) остаётся тем же.
 *
 * Кадр лежит в ORCA_FB_POOL_BASE, так что заодно это дымовой тест FMC.
 */

/*
 * 480x320 — размер будущей панели, в альбомной ориентации. Клиент
 * (tools/fbstream --stream gui, Android) открывает окно ровно под него,
 * поэтому тестовая картинка должна быть той же геометрии: иначе координаты
 * тача, посчитанные клиентом от размера окна, не совпадут с кадром.
 */
#define ORCA_FBTEST_WIDTH   480u
#define ORCA_FBTEST_HEIGHT  320u

/* Требует поднятой SDRAM. Возвращает false, если FMC не инициализирован. */
bool orca_fbtest_init(void);

/*
 * Рендерит кадры и толкает их в fbstream. Пока трансляция выключена,
 * задача спит и не жжёт такты — рисовать некому и незачем.
 */
void orca_fbtest_task(void* arg);

/* Номер отрисованного кадра — для shell `fb status`. */
uint32_t orca_fbtest_frame_count(void);

/*
 * Витки задачи, включая холостые (когда трансляция выключена или выбран
 * другой источник). Ноль означает, что задача не работает вообще — иначе
 * «test не рисует» невозможно отличить от «test не выбран».
 */
uint32_t orca_fbtest_loop_count(void);

#endif /* ORCA_FBTEST_H */
