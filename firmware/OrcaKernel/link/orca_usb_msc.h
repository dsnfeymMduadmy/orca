#ifndef ORCA_USB_MSC_H
#define ORCA_USB_MSC_H

#include <stdbool.h>
#include <stdint.h>

/*
 * USB Mass Storage: хост видит устройство как Orca (строки дескрипторов в
 * Core/Src/usbd_desc.c) с тремя дисками — по одному на каждую память платы:
 *
 *   LUN 0   2 МБ    внутренняя FLASH, образ ядра  — только чтение
 *   LUN 1   16 МБ   QSPI NOR, том FatFs "1:"      — чтение и запись
 *   LUN 2   карта   microSD, том FatFs "0:"       — чтение и запись
 *
 * Три LUN'а, а не три отдельных USB-устройства: у платы один порт, и класс
 * MSC ровно для этого и умеет несколько логических томов на одном интерфейсе.
 *
 * LUN 0 отдаётся только на чтение специально. По этому адресу лежит само
 * работающее ядро: запись в него хостом — это не «испорченный файл», а
 * кирпич с восстановлением через BOOT0 и DFU. Файловой системы там нет,
 * поэтому хост покажет диск нераспознанного формата; смысл LUN'а в том, что
 * прошивку можно снять с живого устройства (dd) и сравнить с образом сборки.
 *
 * Владение носителем
 * ==================
 *
 * У SD и QSPI два потребителя: ядро через FatFs и хост через SCSI. Хост
 * кеширует FAT у себя и не ждёт, что содержимое изменится под ним, поэтому
 * одновременно держать том смонтированным с двух сторон нельзя — это битая
 * ФС. Пока хост подключён, тома ядром размонтированы (см. bsp_storage.h):
 * запись с карты становится недоступна, GUI переходит на встроенные копии
 * страниц, а `ls` отвечает, что тома нет. Как только кабель выдернут, тома
 * монтируются обратно, и кэш списка приложений сбрасывается.
 *
 * Переключением владельца занимается orca_usb_msc_task, а не прерывание:
 * f_mount/f_unmount из ISR вызывать нельзя.
 */

#define ORCA_MSC_LUN_FLASH  0u
#define ORCA_MSC_LUN_QSPI   1u
#define ORCA_MSC_LUN_SD     2u
#define ORCA_MSC_LUN_COUNT  3u

typedef enum {
    ORCA_MSC_OFF = 0,   /* стек не поднялся */
    ORCA_MSC_IDLE,      /* кабеля нет, тома у ядра */
    ORCA_MSC_HOST,      /* хост подключён, тома отданы ему */
} orca_msc_state_t;

/*
 * Поднимает USB Device + класс MSC и заодно монтирует оба тома ядром:
 * хосту носитель должен достаться уже размеченным, а чистый QSPI
 * форматируется именно при монтировании (bsp_qspi_mount).
 */
bool orca_usb_msc_init(void);

/*
 * Следит за состоянием шины и передаёт носители между ядром и хостом.
 * Она же дописывает кеш секторов QSPI, когда хост перестал писать: без
 * этого последний записанный сектор терялся бы при выдёргивании кабеля.
 */
void orca_usb_msc_task(void* arg);

orca_msc_state_t orca_usb_msc_state(void);

/* Короткая метка состояния для GUI и консоли: off / idle / host. */
const char* orca_usb_msc_state_str(void);

/* Счётчики блоков — видно, идёт ли обмен, когда хост «завис» на копировании. */
uint32_t orca_usb_msc_blocks_read(void);
uint32_t orca_usb_msc_blocks_written(void);

#endif /* ORCA_USB_MSC_H */
